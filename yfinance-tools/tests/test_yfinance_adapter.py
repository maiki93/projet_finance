def test_no_isin_and_type_equivalence(mocker, mock_fetch_isin_and_fast_info) -> None:
    # return "currency" and isin '-'
    mock_fetch_isin_and_fast_info({"eurusd": (mocker.MagicMock(quote_type="currency", currency="USD"), "-")})
    adapter = YFinanceAdapter()

    results: IdentifierEntryDict = adapter.fetch_static_identifiers({"eurusd": FinancialIdentifierEntry("DUM")})

