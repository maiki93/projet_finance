def test_fetch_static_identifiers_mock_web(mocker, mock_fetch_isin_and_fast_info) -> None:
    data = {
        "apple": FinancialIdentifierEntry("AAPL"),
        "cac40": FinancialIdentifierEntry("CAC40"),
        "eurusd": FinancialIdentifierEntry("EURUSD"),
    }

    # Prepare custom _YFFastInfo mocks
    apple_fast_info = mocker.MagicMock(quote_type="EQUITY", currency="USD")
    cac_fast_info = mocker.MagicMock(quote_type="INDEX", currency="EUR")
    eurusd_fast_info = mocker.MagicMock(quote_type="currency", currency="EUR")

    mock_fetch_isin_and_fast_info(
        {
            "apple": (apple_fast_info, "US0378331005"),
            "cac40": (cac_fast_info, "FR0003500008"),
            "eurusd": (eurusd_fast_info, None),
        }
    )

    adapter = YFinanceAdapter()

    results: IdentifierEntryDict = adapter.fetch_static_identifiers(data)

    assert len(results) == 3
    assert results["apple"].asset_type == "EQUITY"
    assert results["eurusd"].asset_type == "FOREX"
    assert results["eurusd"].isin is None


